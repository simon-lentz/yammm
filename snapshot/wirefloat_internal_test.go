// wireFloat.MarshalJSON is a copy of encoding/json's float encoder, kept for
// its cost. This holds the two in lockstep so the copy cannot drift, and it is
// the only coverage of the exponent branch and the e-09 → e-9 trim.
func TestWireFloat_MatchesEncodingJSON(t *testing.T) {
	t.Parallel()

	vals := []float64{
		0, 1, -1, 2.5, 0.1, 1860000, math.Pi,
		math.SmallestNonzeroFloat64, math.MaxFloat64,
		1e-6, 9.999999e-7, 1e-7, 1e-9, 1e-10, 1e20, 1e21, 1.0000001e21,
	}
	for e := -320; e <= 308; e++ {
		p := math.Pow(10, float64(e))
		vals = append(vals, p, -p, p*3, p/7)
	}
	for i := range 20000 {
		vals = append(vals, float64(i), float64(i)/7, -float64(i)*1e-8)
	}

	var sawExponent, sawTrim, sawSuffix bool
	for _, v := range vals {
		if math.IsInf(v, 0) || math.IsNaN(v) {
			continue // generated by overflow; a held float is finite
		}
		got, err := wireFloat(v).MarshalJSON()
		if err != nil {
			t.Fatalf("wireFloat(%v).MarshalJSON: %v", v, err)
		}
		want, err := json.Marshal(v)
		if err != nil {
			t.Fatalf("json.Marshal(%v): %v", v, err)
		}
		if !bytes.ContainsAny(want, ".eE") {
			want = append(want, '.', '0')
			sawSuffix = true
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("wireFloat(%v) = %s, encoding/json + suffix = %s", v, got, want)
		}
		if bytes.ContainsAny(got, "eE") {
			sawExponent = true
			// The trim fires only on a zero-padded NEGATIVE exponent, so a
			// positive one can never be a trim case.
			if bytes.Contains(got, []byte("e-9")) {
				sawTrim = true
			}
		}
	}

	// Corpus floor: without these the comparison above can pass vacuously.
	if !sawExponent {
		t.Error("corpus never reached the exponent branch")
	}
	if !sawTrim {
		t.Error("corpus never reached a single-digit exponent, where the trim applies")
	}
	if !sawSuffix {
		t.Error("corpus never reached a whole float, where the .0 suffix applies")
	}
}

// Every float element of a vector emits with a float indicator, whole or
// fractional, and an integer element is written as held: the reader reads every
// number literal at a Vector element as its nearest float64.
func TestWireValue_AVectorsFloatsEmitAsFloats(t *testing.T) {
	t.Parallel()
	got := wireValue([]any{float64(1), 2.5, int64(3)}, schema.VectorConstraint{})
	elems, ok := got.([]any)
	if !ok {
		t.Fatalf("wireValue returned %T, want []any", got)
	}
	if len(elems) != 3 {
		t.Fatalf("got %d elements, want 3", len(elems))
	}
	for i, e := range elems[:2] {
		if _, ok := e.(json.Marshaler); !ok {
			t.Errorf("element %d is %T, which is no wire float — it would emit int-shaped", i, e)
		}
	}
	if elems[2] != int64(3) {
		t.Errorf("element 2 is %#v, want the int64 as held", elems[2])
	}

	// A document can state a string under a Vector; it passes through untouched,
	// or the assertions above would hold for anything.
	if got := wireValue("not a vector", schema.VectorConstraint{}); got != "not a vector" {
		t.Errorf("wireValue over a string returned %#v, want it untouched", got)
	}
}
